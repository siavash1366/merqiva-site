function applyLang(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir =
    lang === "ar" ? "rtl" : "ltr";

  document
    .querySelectorAll("[data-t]")
    .forEach(el => {
      const key = el.dataset.t;

      if (T[lang][key]) {
        el.textContent = T[lang][key];
      }
    });

  document
    .querySelectorAll(".lang")
    .forEach(button => {
      button.classList.toggle(
        "active",
        button.dataset.lang === lang
      );
    });

  if (lang === "ar") {
    document.title =
      "Merqiva | استخبارات المبيعات البحرية في دول الخليج";

    document
      .querySelector('meta[name="description"]')
      .setAttribute(
        "content",
        "تساعد Merqiva موردي القطاع البحري على تحديد المشترين المناسبين في دول الخليج من خلال أبحاث الأساطيل وصنّاع القرار وإشارات الشراء."
      );
  } else {
    document.title =
      "Merqiva | GCC Maritime Sales Intelligence";

    document
      .querySelector('meta[name="description"]')
      .setAttribute(
        "content",
        "Merqiva researches GCC maritime buyers, fleets, decision-makers and buying signals to identify sales opportunities worth pursuing."
      );
  }

  try {
    localStorage.setItem(
      "merqiva-language",
      lang
    );
  } catch (_) {}
}


/* Language buttons */
document
  .querySelectorAll(".lang")
  .forEach(button => {
    button.addEventListener(
      "click",
      () => applyLang(button.dataset.lang)
    );
  });


/* Load saved language */
let initialLang = "en";

try {
  const savedLang =
    localStorage.getItem(
      "merqiva-language"
    );

  if (
    savedLang === "ar" ||
    savedLang === "en"
  ) {
    initialLang = savedLang;
  }
} catch (_) {}

applyLang(initialLang);


/* Contact form */
const contactForm =
  document.getElementById("contactForm");

const submitBtn =
  document.getElementById("submitBtn");

const formStatus =
  document.getElementById("formStatus");


if (
  contactForm &&
  submitBtn &&
  formStatus
) {

  contactForm.addEventListener(
    "submit",
    async event => {

      event.preventDefault();

      const currentLang =
        document.documentElement.lang === "ar"
          ? "ar"
          : "en";


      /* Clear previous status */
      formStatus.className =
        "form-status";

      formStatus.textContent = "";


      /* Browser validation */
      if (!contactForm.checkValidity()) {
        contactForm.reportValidity();
        return;
      }


      /* Turnstile validation */
      const token =
        contactForm.querySelector(
          'input[name="cf-turnstile-response"]'
        )?.value;

      if (!token) {
        formStatus.textContent =
          T[currentLang].turnstilemsg;

        formStatus.className =
          "form-status error show";

        return;
      }


      /* Sending state */
      submitBtn.disabled = true;

      submitBtn.textContent =
        T[currentLang].sending;


      try {

        const response =
          await fetch(
            "/api/contact",
            {
              method: "POST",
              body: new FormData(
                contactForm
              ),
              headers: {
                "Accept":
                  "application/json"
              }
            }
          );


        let result = {};

        try {
          result =
            await response.json();
        } catch (_) {}


        /*
         * Rate Limit:
         * 5 submissions / 10 minutes
         */
        if (response.status === 429) {

          const responseLang =
            document.documentElement.lang === "ar"
              ? "ar"
              : "en";

          formStatus.textContent =
            T[responseLang].ratelimitmsg;

          formStatus.className =
            "form-status error show";

          if (window.turnstile) {
            window.turnstile.reset();
          }

          return;
        }


        /* Other API errors */
        if (
          !response.ok ||
          !result.success
        ) {
          throw new Error(
            result.error ||
            "submit_failed"
          );
        }


        /* Success */
        const responseLang =
          document.documentElement.lang === "ar"
            ? "ar"
            : "en";

        formStatus.textContent =
          T[responseLang].successmsg;

        formStatus.className =
          "form-status success show";

        contactForm.reset();

        if (window.turnstile) {
          window.turnstile.reset();
        }

      } catch (error) {

        console.error(
          "Contact form error:",
          error
        );

        const responseLang =
          document.documentElement.lang === "ar"
            ? "ar"
            : "en";

        formStatus.textContent =
          error.message &&
          error.message !==
            "submit_failed"
            ? error.message
            : T[responseLang].errormsg;

        formStatus.className =
          "form-status error show";

        if (window.turnstile) {
          window.turnstile.reset();
        }

      } finally {

        const responseLang =
          document.documentElement.lang === "ar"
            ? "ar"
            : "en";

        submitBtn.disabled = false;

        submitBtn.textContent =
          T[responseLang].send;
      }
    }
  );
}
